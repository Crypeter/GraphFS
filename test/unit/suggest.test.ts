import { test } from 'node:test'
import assert from 'node:assert/strict'
import {
  localizedPair,
  parseGeneratedHeader,
  parseMarkdownLinks,
  parsePythonImports,
  resolvePythonModule,
  suggestEdges,
} from '../../src/importers/suggest.ts'

test('parsePythonImports：plain / from / as / 多模块', () => {
  const specs = parsePythonImports(`
import os
import a, b as c
from .models import X
from model.PA import y
# import ignored
`)
  assert.deepEqual(
    specs.map((s) => s.module),
    ['os', 'a', 'b', '.models', 'model.PA'],
  )
})

test('resolvePythonModule：同目录、相对导入、root 相对', () => {
  const files = new Set(['pkg/models.py', 'pkg/main.py', 'pkg/sub/util.py', 'top.py'])
  assert.equal(resolvePythonModule('pkg', { module: 'models', raw: 'models' }, files), 'pkg/models.py')
  assert.equal(resolvePythonModule('pkg/sub', { module: '..models', raw: '..models' }, files), 'pkg/models.py')
  assert.equal(resolvePythonModule('pkg', { module: 'top', raw: 'top' }, files), 'top.py')
  assert.equal(resolvePythonModule('pkg', { module: 'nope', raw: 'nope' }, files), null)
})

test('parseMarkdownLinks：跳过外链与纯锚点', () => {
  const links = parseMarkdownLinks(`
[a](./a.md) [b](b.py#L3) [c](https://x.y/z) [d](#section) [e](mailto:a@b)
`)
  assert.deepEqual(links, ['./a.md', 'b.py#L3'])
})

test('parseGeneratedHeader', () => {
  assert.equal(parseGeneratedHeader('// @generated from src/api.ts\ncode'), 'src/api.ts')
  assert.equal(parseGeneratedHeader('# generated by hand\n'), null)
})

test('localizedPair 双向识别', () => {
  const files = new Set(['README.md', 'README.zh.md', 'doc.md'])
  assert.deepEqual(localizedPair('README.zh.md', files), { base: 'README.md', translation: 'README.zh.md' })
  assert.deepEqual(localizedPair('README.md', files), { base: 'README.md', translation: 'README.zh.md' })
  assert.equal(localizedPair('doc.md', files), null)
})

test('suggestEdges 端到端：import / 链接 / generated / 译文', async () => {
  const files = ['README.md', 'README.zh.md', 'main.py', 'models.py', 'docs/api.md', 'src/api.ts']
  const contents: Record<string, string> = {
    'README.md': '# R\n\nsee [docs](./docs/api.md) and [main](./main.py)\n',
    'README.zh.md': '# R\n\n见 [文档](./docs/api.md)\n',
    'main.py': 'from models import M\n',
    'models.py': 'class M: pass\n',
    'docs/api.md': '<!-- @generated from src/api.ts -->\n',
    'src/api.ts': 'export class Api {}\n',
  }

  const candidates = await suggestEdges({ files, read: async (p) => contents[p] ?? null })
  const has = (from: string, to: string, relation: string): boolean =>
    candidates.some((c) => c.from === from && c.to === to && c.relation === relation)

  assert.ok(has('models', 'main', 'constrains'), '模块 → 使用方')
  assert.ok(has('docs-api', 'readme', 'documents'), '代码 → 文档')
  assert.ok(has('src-api', 'docs-api', 'generates'), '@generated')
  assert.ok(has('readme', 'readme-zh', 'translates'), '译文对')
})

test('suggestEdges：同一对文件的多条证据只留置信度最高的', async () => {
  const files = ['a.md', 'b.py']
  const candidates = await suggestEdges({
    files,
    read: async (p) => (p === 'a.md' ? '[b](./b.py)\n[b](./b.py)\n' : ''),
  })
  assert.equal(candidates.filter((c) => c.relation === 'documents').length, 1)
})

test('suggestEdges：TypeScript import 也能发现（constrains，模块 → 使用方）', async () => {
  const files = ['src/a.ts', 'src/b.ts']
  const contents: Record<string, string> = {
    'src/a.ts': 'export const a = 1\n',
    'src/b.ts': "import { a } from './a.ts'\nexport const b = a + 1\n",
  }
  const candidates = await suggestEdges({ files, read: async (p) => contents[p] ?? null })
  const found = candidates.find((c) => c.fromPath === 'src/a.ts' && c.toPath === 'src/b.ts')
  assert.ok(found, JSON.stringify(candidates))
  assert.equal(found.relation, 'constrains')
  assert.equal(found.confidence, 0.8)
})

